def seed_database():
    init_db()
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    
    cursor.execute("DELETE FROM change_logs")
    cursor.execute("DELETE FROM scholarships")
    cursor.execute("DELETE FROM sqlite_sequence WHERE name='scholarships' OR name='change_logs'")
    
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    for item in REAL_SCHOLARSHIPS:
        reasons_json = json.dumps(item["confidence_reasons"])
        cursor.execute("""
        INSERT INTO scholarships (
            name, provider, official_source_url, application_url, source_type,
            amount, eligibility, academic_reqs, course_level, income_criteria,
            age_criteria, gender_criteria, category_criteria, domicile_reqs,
            institution_reqs, opening_date, closing_date, documents_req,
            selection_process, renewal_reqs, status, confidence_score,
            confidence_reasons, last_verified, evidence_text, created_at, updated_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            item["name"], item["provider"], item["official_source_url"], item["application_url"],
            item["source_type"], item["amount"], item["eligibility"], item["academic_reqs"],
            item["course_level"], item["income_criteria"], item["age_criteria"], item["gender_criteria"],
            item["category_criteria"], item["domicile_reqs"], item["institution_reqs"],
            item["opening_date"], item["closing_date"], item["documents_req"], item["selection_process"],
            item["renewal_reqs"], item["status"], item["confidence_score"], reasons_json,
            now_str, item["evidence_text"], now_str, now_str
        ))
        
        scholarship_id = cursor.lastrowid
        
        if "changes" in item:
            for change in item["changes"]:
                cursor.execute("""
                INSERT INTO change_logs (
                    scholarship_id, field_name, old_value, new_value, date_detected, official_source_url, evidence_text
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
                """, (
                    scholarship_id, change["field_name"], change["old_value"], change["new_value"],
                    change["date_detected"], change["official_source_url"], change["evidence_text"]
                ))
                
    conn.commit()
    conn.close()
    print("Database successfully seeded with 22 authentic scholarship records!")

